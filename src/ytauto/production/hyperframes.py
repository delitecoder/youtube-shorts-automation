"""HyperFrames renderer (HeyGen, Apache-2.0): storyboard -> animated HTML/GSAP composition -> MP4.

Why: richer motion than frame-by-frame Pillow drawing (eased transitions, kinetic text, particles,
light sweeps, Ken Burns images, word-pop captions) while staying deterministic and CPU-only:
HyperFrames seeks every frame in headless Chromium and encodes with FFmpeg. The composition is
generated by fixed code here, so it costs no Claude tokens per video.

Audio is NOT part of the HTML: the narration+music+SFX mix from sound.py is muxed afterwards, so
loudness and A/V sync QC stay identical to the Pillow renderer (which remains the fallback).
Requires: Node 22+, `npm ci --prefix renderer/hyperframes`, a Chromium (pre-installed in Claude
cloud containers). Telemetry is disabled before every render.
"""
from __future__ import annotations

import html
import json
import random
import re
import shutil
import subprocess
from pathlib import Path

W, H, FPS = 1080, 1920, 30
ROOT = Path(__file__).resolve().parents[3]
RENDERER_DIR = ROOT / "renderer" / "hyperframes"
ACCENTS = ["#22d3ee", "#fbbf24", "#f472b6", "#a3e635"]
KEYWORDS = {"def", "return", "class", "import", "from", "for", "in", "if", "else", "while", "async",
            "await", "const", "let", "function", "True", "False", "None"}


class HyperframesUnavailable(RuntimeError):
    pass


def available() -> bool:
    return (RENDERER_DIR / "node_modules" / ".bin" / "hyperframes").exists() and shutil.which("node") is not None


def e(s) -> str:
    return html.escape(str(s), quote=True)


# ------------------------------------------------------------------ visuals (HTML + GSAP)
def _visual(i: int, v: dict, t0: float, dur: float, accent: str, images: dict) -> tuple[str, list[str]]:
    """Returns (html, list of GSAP statements). All times are absolute seconds."""
    k, sid, js = v["type"], f"s{i}", []
    a = f"{t0 + 0.35:.3f}"
    if k == "title":
        words = "".join(f'<span class="w">{e(w)}</span> ' for w in v["headline"].split())
        out = f'<div class="title"><h1 id="{sid}h">{words}</h1>'
        if v.get("kicker"):
            out += f'<div class="kicker" id="{sid}k">{e(v["kicker"])}</div>'
        out += f'<div class="bar" id="{sid}b" style="background:{accent}"></div></div>'
        js += [f'tl.from("#{sid}h .w",{{y:90,opacity:0,rotation:4,stagger:0.07,duration:0.6,ease:"back.out(1.7)"}},{a});',
               f'tl.from("#{sid}k",{{opacity:0,x:-40,duration:0.5}},{t0 + 0.8:.3f});',
               f'tl.from("#{sid}b",{{scaleX:0,transformOrigin:"left",duration:0.8,ease:"power3.out"}},{t0 + 0.6:.3f});']
    elif k == "bullets":
        items = "".join(f'<li id="{sid}i{j}"><span class="dot" style="background:{accent}"></span>{e(x)}</li>'
                        for j, x in enumerate(v["items"][:4]))
        out = f'<ul class="bullets">{items}</ul>'
        step = max(0.5, (dur - 1.0) / max(len(v["items"][:4]), 1))
        for j in range(len(v["items"][:4])):
            js.append(f'tl.from("#{sid}i{j}",{{x:-120,opacity:0,duration:0.55,ease:"power3.out"}},{t0 + 0.3 + j * step:.3f});')
    elif k == "code":
        lines = v["code"].splitlines()[:12]
        rows = []
        for j, line in enumerate(lines):
            toks = "".join(f'<span class="{"kw" if t in KEYWORDS else "num" if t.isdigit() else ""}" '
                           f'style="{"color:" + accent if t in KEYWORDS else ""}">{e(t)}</span>'
                           for t in re.findall(r"\s+|\w+|[^\w\s]", line))
            rows.append(f'<div class="cl" id="{sid}l{j}">{toks or "&nbsp;"}</div>')
        out = (f'<div class="code" style="border-color:{accent}"><div class="dots"><i></i><i></i><i></i></div>'
               f'{"".join(rows)}<span class="caret" id="{sid}c" style="background:{accent}"></span></div>')
        js.append(f'tl.from("#{sid} .code",{{y:60,opacity:0,scale:0.96,duration:0.5}},{t0 + 0.2:.3f});')
        for j in range(len(lines)):
            js.append(f'tl.from("#{sid}l{j}",{{clipPath:"inset(0 100% 0 0)",duration:0.45,ease:"none"}},{t0 + 0.5 + j * 0.35:.3f});')
        js.append(f'tl.to("#{sid}c",{{opacity:0,repeat:{int(dur / 0.5)},yoyo:true,duration:0.25,ease:"steps(1)"}},{t0:.3f});')
    elif k == "diagram":
        nodes = v["nodes"][:5]
        parts = []
        for j, n in enumerate(nodes):
            parts.append(f'<div class="node" id="{sid}n{j}" style="border-color:{ACCENTS[j % 4]}">{e(n)}</div>')
            if j < len(nodes) - 1:
                parts.append(f'<div class="arrow" id="{sid}a{j}" style="background:{accent}"></div>')
        out = f'<div class="diagram">{"".join(parts)}</div>'
        step = max(0.45, (dur - 1.0) / max(len(nodes), 1))
        for j in range(len(nodes)):
            tj = t0 + 0.3 + j * step
            js.append(f'tl.from("#{sid}n{j}",{{scale:0.6,opacity:0,duration:0.45,ease:"back.out(2)"}},{tj:.3f});')
            if j < len(nodes) - 1:
                js.append(f'tl.from("#{sid}a{j}",{{scaleY:0,transformOrigin:"top",duration:0.3}},{tj + 0.3:.3f});')
    elif k == "stat":
        m = re.match(r"^([^\d]*)([\d.,]+)(.*)$", str(v["value"]))
        if m:
            num = float(m.group(2).replace(",", ""))
            dec = len(m.group(2).split(".")[1]) if "." in m.group(2) else 0
            out = (f'<div class="stat"><div class="big" id="{sid}v" style="color:{accent}">{e(v["value"])}</div>'
                   f'<div class="label" id="{sid}lab">{e(v["label"])}</div></div>')
            js.append(f'(function(){{const o={{v:0}},el=document.getElementById("{sid}v");'
                      f'tl.to(o,{{v:{num},duration:1.6,ease:"power2.out",onUpdate:()=>{{el.textContent='
                      f'{json.dumps(m.group(1))}+o.v.toLocaleString("en-US",{{minimumFractionDigits:{dec},'
                      f'maximumFractionDigits:{dec}}})+{json.dumps(m.group(3))};}}}},{t0 + 0.3:.3f});}})();')
        else:
            out = (f'<div class="stat"><div class="big" id="{sid}v" style="color:{accent}">{e(v["value"])}</div>'
                   f'<div class="label" id="{sid}lab">{e(v["label"])}</div></div>')
        js += [f'tl.from("#{sid}v",{{scale:0.4,opacity:0,duration:0.6,ease:"back.out(2)"}},{t0 + 0.25:.3f});',
               f'tl.from("#{sid}lab",{{y:40,opacity:0,duration:0.5}},{t0 + 0.9:.3f});']
    elif k == "comparison":
        def card(side, col):
            c = v[side]
            lis = "".join(f"<li>{e(x)}</li>" for x in c.get("items", [])[:4])
            return f'<div class="card" id="{sid}{side}" style="border-color:{col}"><h3 style="color:{col}">{e(c["title"])}</h3><ul>{lis}</ul></div>'
        out = f'<div class="compare">{card("left", ACCENTS[2])}<div class="vs" id="{sid}vs">VS</div>{card("right", ACCENTS[0])}</div>'
        js += [f'tl.from("#{sid}left",{{x:-500,opacity:0,duration:0.6,ease:"power3.out"}},{a});',
               f'tl.from("#{sid}right",{{x:500,opacity:0,duration:0.6,ease:"power3.out"}},{t0 + 0.7:.3f});',
               f'tl.from("#{sid}vs",{{scale:0,rotation:-90,duration:0.5,ease:"back.out(3)"}},{t0 + 1.1:.3f});']
    elif k == "timeline":
        evs = v["events"][:5]
        items = "".join(f'<div class="ev" id="{sid}e{j}"><span class="pin" style="background:{ACCENTS[j % 4]}"></span>'
                        f'<b style="color:{ACCENTS[j % 4]}">{e(x["label"])}</b><p>{e(x.get("text", ""))}</p></div>'
                        for j, x in enumerate(evs))
        out = f'<div class="timeline"><div class="line" id="{sid}ln" style="background:{accent}"></div>{items}</div>'
        js.append(f'tl.from("#{sid}ln",{{scaleY:0,transformOrigin:"top",duration:max(1,{dur:.2f}*0.6),ease:"none"}},{t0 + 0.2:.3f});'
                  .replace("max(1,", "Math.max(1,"))
        step = max(0.6, (dur - 1.0) / max(len(evs), 1))
        for j in range(len(evs)):
            js.append(f'tl.from("#{sid}e{j}",{{x:80,opacity:0,duration:0.5,ease:"power3.out"}},{t0 + 0.4 + j * step:.3f});')
    elif k == "question":
        words = "".join(f'<span class="w">{e(w)}</span> ' for w in v["question"].split())
        out = (f'<div class="question"><h1 id="{sid}q">{words}</h1>'
               f'<div class="ring" id="{sid}r" style="border-color:{accent};color:{accent}">?</div></div>')
        js += [f'tl.from("#{sid}q .w",{{y:60,opacity:0,stagger:0.08,duration:0.5,ease:"power3.out"}},{a});',
               f'tl.from("#{sid}r",{{scale:0,duration:0.6,ease:"elastic.out(1,0.5)"}},{t0 + 0.9:.3f});',
               f'tl.to("#{sid}r",{{scale:1.12,repeat:{max(1, int(dur / 0.7))},yoyo:true,duration:0.35}},{t0 + 1.5:.3f});']
    elif k == "image":
        name = Path(v["asset"]).name
        f = v.get("focus") or [0.25, 0.25, 0.75, 0.75]
        fx, fy = (f[0] + f[2]) / 2, (f[1] + f[3]) / 2
        out = (f'<div class="imgwrap" id="{sid}w" style="border-color:{accent}">'
               f'<img id="{sid}img" src="assets/{e(name)}" style="transform-origin:{fx * 100:.1f}% {fy * 100:.1f}%">'
               f'<div class="sweep" id="{sid}sw"></div><div class="vignette"></div></div>'
               + (f'<div class="imgcap" id="{sid}cap">{e(v.get("caption", ""))}</div>' if v.get("caption") else ""))
        js += [f'tl.from("#{sid}w",{{clipPath:"inset(50% 50% 50% 50% round 32px)",duration:0.7,ease:"power3.inOut"}},{t0 + 0.15:.3f});',
               f'tl.fromTo("#{sid}img",{{scale:1.0}},{{scale:1.15,duration:{max(dur, 1):.2f},ease:"none"}},{t0:.3f});',
               f'tl.fromTo("#{sid}sw",{{x:"-120%"}},{{x:"220%",duration:1.1,ease:"power2.inOut"}},{t0 + 0.6:.3f});']
        if v.get("caption"):
            js.append(f'tl.from("#{sid}cap",{{y:30,opacity:0,duration:0.4}},{t0 + 0.8:.3f});')
    elif k == "subscribe":
        out = (f'<div class="sub"><div class="btn" id="{sid}btn">SUBSCRIBE</div>'
               f'<div class="btn done" id="{sid}done">SUBSCRIBED ✓</div>'
               f'<div class="bell" id="{sid}bell">🔔</div><p id="{sid}t">A new tech story every day</p></div>')
        press = t0 + dur * 0.55
        js += [f'tl.from("#{sid}btn",{{scale:0,duration:0.5,ease:"back.out(2.5)"}},{t0 + 0.2:.3f});',
               f'tl.set("#{sid}done",{{opacity:0}},{t0:.3f});',
               f'tl.to("#{sid}btn",{{scale:0.9,duration:0.12,yoyo:true,repeat:1}},{press - 0.2:.3f});',
               f'tl.to("#{sid}done",{{opacity:1,duration:0.2}},{press:.3f});',
               f'tl.to("#{sid}btn",{{opacity:0,duration:0.2}},{press:.3f});',
               f'tl.from("#{sid}bell",{{scale:0,duration:0.4,ease:"back.out(3)"}},{t0 + 0.5:.3f});',
               f'tl.to("#{sid}bell",{{rotation:18,repeat:7,yoyo:true,duration:0.09,transformOrigin:"50% 0%"}},{press + 0.1:.3f});',
               f'tl.from("#{sid}t",{{opacity:0,y:20,duration:0.4}},{t0 + 0.9:.3f});']
    else:
        out = f'<div class="title"><h1>{e(v.get("headline", ""))}</h1></div>'
    return out, js


