def build(storyboard: dict, timings: list[dict], caps: list[dict], workdir: Path,
          series_label: str = "TECH IN 60s", logo: str | None = None) -> Path:
    """Write <workdir>/hf/index.html (+ gsap + assets) and return the project dir."""
    proj = workdir / "hf"
    if proj.exists():
        shutil.rmtree(proj)
    (proj / "assets").mkdir(parents=True)
    shutil.copy(RENDERER_DIR / "node_modules" / "gsap" / "dist" / "gsap.min.js", proj / "gsap.min.js")
    for f in (workdir / "assets").glob("*") if (workdir / "assets").exists() else []:
        if f.is_file():
            shutil.copy(f, proj / "assets" / f.name)
    duration = timings[-1]["end"]
    scenes = storyboard["scenes"]
    rnd = random.Random(sum(storyboard.get("video_id", "x").encode()))
    body, js = [], []

    # ambient: drifting grid + particles + progress bar (finite repeats keep the timeline seekable)
    body.append('<div class="grid" id="grid"></div>')
    js.append(f'tl.to("#grid",{{y:60,duration:{duration:.2f},ease:"none"}},0);')
    for p in range(14):
        x, y, col = rnd.randint(40, 1040), rnd.randint(200, 1800), ACCENTS[p % 4]
        body.append(f'<div class="particle" id="p{p}" style="left:{x}px;top:{y}px;background:{col}"></div>')
        js.append(f'tl.to("#p{p}",{{y:-{rnd.randint(120, 380)},x:{rnd.randint(-60, 60)},opacity:{rnd.uniform(.2, .8):.2f},'
                  f'duration:{duration:.2f},ease:"sine.inOut"}},0);')
    if logo:                                   # brand badge: pops in, pulses on every scene change
        body.append(f'<img class="logo" id="logo" src="{e(logo)}">')
        js.append('tl.from("#logo",{scale:0,rotation:-25,duration:0.5,ease:"back.out(2)"},0);')
        for tm in timings[1:]:
            js.append(f'tl.fromTo("#logo",{{scale:1.18}},{{scale:1,duration:0.3,ease:"power2.out"}},{tm["start"]:.3f});')
    body.append(f'<div class="top{" withlogo" if logo else ""}">{e(series_label)}</div>')
    dashes = "".join(f'<i id="ch{k}"></i>' for k in range(len(storyboard["scenes"])))
    body.append(f'<div class="chapters">{dashes}</div>')
    for k, tm in enumerate(timings):
        js.append(f'tl.set("#ch{k}",{{background:"{ACCENTS[k % 4]}"}},{tm["start"]:.3f});')
    body.append(f'<div class="progress" id="prog" style="background:{ACCENTS[0]}"></div>')
    js.append(f'tl.fromTo("#prog",{{scaleX:0}},{{scaleX:1,duration:{duration:.2f},ease:"none"}},0);')

    custom_report: list[dict] = []
    for i, (s, tm) in enumerate(zip(scenes, timings)):
        t0, dur = tm["start"], tm["end"] - tm["start"]
        accent = ACCENTS[i % 4]
        v = s["visual"]
        full_frame = False
        if v.get("type") == "custom":                 # camera-man code, checked before use
            from .custom_scene import SceneRejected, load, wrap_js
            prefix = f"s{i}-"
            try:
                html_c, js_c = load(workdir, v.get("code", f"scene{i + 1}"), prefix)
                vis_html, vis_js = html_c, [wrap_js(js_c, t0, dur, prefix)]
                full_frame = bool(v.get("full_frame"))
                custom_report.append({"scene": i + 1, "status": "used"})
            except SceneRejected as ex:
                custom_report.append({"scene": i + 1, "status": "fallback", "reason": str(ex)[:300]})
                vis_html, vis_js = _visual(i, {"type": "title", "headline": s.get("on_screen_text") or " "},
                                           t0, dur, accent, {})
        else:
            vis_html, vis_js = _visual(i, v, t0, dur, accent, {})
        head_words = "".join(f'<span class="w">{e(w)}</span> ' for w in s.get("on_screen_text", "").split())
        head = "" if full_frame else f'<div class="head" id="s{i}hd" style="color:{accent}">{head_words}</div>'
        inner = f'<div class="custom-full">{vis_html}</div>' if full_frame else f'<div class="vis">{vis_html}</div>'
        body.append(f'<div class="scene clip" id="s{i}" data-start="{t0:.3f}" data-duration="{dur:.3f}" data-track-index="1">'
                    f'{head}{inner}</div>')
        trans = s.get("transition", "fade")
        if i > 0 and trans != "cut":
            frm = '{x:160,opacity:0}' if trans == "slide" else '{opacity:0,scale:1.04}'
            js.append(f'tl.from("#s{i}",{{...{frm},duration:0.35,ease:"power2.out"}},{t0:.3f});')
        if not full_frame:
          js.append(f'tl.from("#s{i}hd .w",{{y:30,opacity:0,stagger:0.05,duration:0.4,ease:"power3.out"}},{t0 + 0.05:.3f});')
        js += vis_js

    for c_i, c in enumerate(caps):
        spans = " ".join(f'<span id="c{c_i}w{j}">{e(w[0])}</span>' for j, w in enumerate(c["words"]))
        start = max(0.0, c["start"] - 0.05)
        nxt = caps[c_i + 1]["start"] - 0.05 if c_i + 1 < len(caps) else duration
        end = min(duration, c["end"] + 0.15, nxt)          # never overlap the next caption
        start, end = round(start, 3), round(end, 3)           # round ends, then derive duration
        body.append(f'<div class="cap clip" data-start="{start:.3f}" data-duration="{max(end - start, 0.1):.3f}" '
                    f'data-track-index="2">{spans}</div>')
        si = next((k for k, tm in enumerate(timings) if c["start"] < tm["end"]), 0)
        for j, w in enumerate(c["words"]):
            js.append(f'tl.to("#c{c_i}w{j}",{{color:"{ACCENTS[si % 4]}",scale:1.12,duration:0.08}},{w[1]:.3f});')
            js.append(f'tl.to("#c{c_i}w{j}",{{color:"#ffffff",scale:1,duration:0.08}},{w[2]:.3f});')

    doc = (f'<!doctype html><html><head><meta charset="utf-8"><style>{CSS}</style></head><body>'
           f'<div id="stage" data-composition-id="main" data-start="0" data-duration="{duration:.3f}" '
           f'data-width="{W}" data-height="{H}" data-fps="{FPS}">{"".join(body)}</div>'
           f'<script src="gsap.min.js"></script><script>const tl=gsap.timeline({{paused:true}});\n'
           + "\n".join(js) +
           '\ntl.set({}, {}, ' + f'{duration:.3f}' + ');\nwindow.__timelines=window.__timelines||{};window.__timelines.main=tl;</script>'
           '</body></html>')
    (proj / "index.html").write_text(doc, encoding="utf-8")
    if custom_report:
        import json as _json
        (workdir / "custom_scenes_report.json").write_text(_json.dumps(custom_report, indent=1))
    return proj


def render(proj: Path, audio_wav: Path, out_mp4: Path, duration: float, timeout: int = 1800) -> None:
    if not available():
        raise HyperframesUnavailable("run: npm ci --prefix renderer/hyperframes")
    hf = str(RENDERER_DIR / "node_modules" / ".bin" / "hyperframes")
    subprocess.run([hf, "telemetry", "disable"], capture_output=True, timeout=60)
    silent = proj.parent / "hf_video.mp4"
    r = subprocess.run([hf, "render", str(proj), "-o", str(silent), "--fps", str(FPS), "--quality", "delivery",
                        "--quiet", "--no-best-effort"], capture_output=True, text=True, timeout=timeout)
    if r.returncode != 0 or not silent.exists():
        raise RuntimeError(f"hyperframes render failed: {(r.stderr or r.stdout)[-400:]}")
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(silent), "-i", str(audio_wav), "-map", "0:v", "-map", "1:a",
                    "-c:v", "libx264", "-preset", "veryfast", "-crf", "18", "-pix_fmt", "yuv420p", "-profile:v", "high",
                    "-r", str(FPS), "-g", "60", "-c:a", "aac", "-b:a", "192k", "-ar", "48000", "-ac", "2",
                    "-t", f"{duration:.3f}", "-movflags", "+faststart", str(out_mp4)], check=True)
